절대 상한선: Group A + 전술적 장기 합산 비중은 최대 50%로 제한하며, 초과 시 모멘텀 훼손 종목(MACD < 0) 매도 후 타점 종목 교체 중심의 로테이션만 허용한다.
리밸런싱 허용 오차: 자산 그룹 전체 비중 ±5%p 이탈 또는 개별 종목 비중 목표 대비 ±10%p 초과 이탈 시 실행한다.

3. 기술적 지표 매트릭스 및 교차 검증 (Technical Matrix)
RSI & STOCHRSI 역할 분담: RSI는 대세적 위치 및 지지선 파악에 사용하고, STOCHRSI는 세부 진입 트리거로 활용한다.
[개정] 1순위 진입 타점 (이원화 교차 검증):
[Type A] 주도주 건강한 눌림목: MACD > 0 AND ADX(14) ≥ 25 AND RSI 50~60 AND STOCHRSI < 40 (조건 완화로 강세장 기회 포착).
[Type B] 우량주 단기 투매 낙폭 과대: MACD < 0 AND MACD 히스토그램 2거래일 연속 상승(수축) AND RSI 40~45 AND STOCHRSI < 20 (원천 지표 STOCH(9,6) ≤ 40 동반 확인 필수. 데이터 공백 시 STOCHRSI 최하단 임계값으로 교차 검증).
진입 금지 조건: -DI > +DI 상태에서 ADX(14) ≥ 25로 급등하는 대세 하락장이나, RSI ≥ 70인 과매수 종목은 신규 자금 투입을 절대 배제한다. (단, 데이터상 방향성 지표인 +DI, -DI가 공백일 경우 ADX 단독 추세 및 주가-이평선 역배열 심화 여부로 가짜 돌파를 상쇄함).
환율 리스크 대응: USD/KRW 환율이 최근 1년 평균 대비 +80원 초과 시 해외 자산 직접 진입을 제한하고, Group B 타점 발생 시 환헤지(H) ETF로 우회 진입한다. (기준 산출을 위해 환율의 1년 평균값 및 표준편차 변화 추이를 시스템 변수에 연동함).

4. 리스크 관리 및 청산 프로토콜 (Risk & Exit)
단기 전술 (Group A): 1차 지지선은 현재가와 가장 가까운 MA1(5일선) 또는 MA2(20일선)로 설정하거나 절대 손절선(-5% ~ -8%)을 적용하여 이탈 시 즉각 비중 축소한다.
전술적 장기 (테마/섹터 ETF): RSI ≥ 70 또는 MACD < 0 발생 시 부분 익절을 진행하되 ADX(14)로 추세를 필터링한다.
[시나리오 A]: 가격 지지 및 ADX(14) ≥ 30 유지 시 매도 보류 또는 최소 비중(10~15%)만 익절한다.
[시나리오 B]: MACD < 0 AND ADX(14) < 25 동반 발생 시 모멘텀 둔화 확정으로 간주하여 30~50% 적극 익절한다.

5. 시스템 예외 프로토콜 (Pre-emptive Overrides)
[예외 8 (우선순위 0순위)] 우량주 강제 청산 및 폭락장 선제 방어 (가치 함정 방어): EPS 역성장 전환 또는 ROE 2분기 연속 10% 하회 시 Group A로 강등한다. 주가가 최고가 대비 -20% 하락 및 주요 지지선(120일선) 이탈 시 선제적 방어를 위해 1차 기계적 비중 축소(25%)를 실행한다. 이후 52주 최고가 대비 -30% 이상 하락, MACD < 0, -DI > +DI 상태에서 ADX ≥ 40 급등 시 대세 폭락으로 규정하고 보유 비중 50%를 시장가 매도한다. (+DI, -DI 공백 시에는 120일선 하회 및 공포/탐욕 지수 20 미만 동반 지속성으로 대체 규정함).
[예외 1] Group B 자산 딥밸류 무한매집 (적극 활용 권장): 1순위 기술적 타점(Type A/B)이 발생하지 않는 관망 국면에서 최우선적으로 가동한다. RSI < 30, 주가 < MA4(120일선), 현재가 ≤ 52주 최저가 대비 +5% 이내, 거래량 ≤ 3개월 평균의 1.0배 조건을 동시 만족하며, 단기 이평선(5일선) 위로 주가가 올라타거나 양봉 캔들(또는 도지형)이 출현한 다음 날 종가 기준으로 하락 브레이크가 확인되었을 때 비중 한도에 구애받지 않고 적극 매집한다. (단, [예외 8] 미발동 시에만 한함).
[예외 2] 기계적 적립식 매수 충돌 방지: 연금저축 및 Group B 정기 적립식 매수는 단기 기술적 필터링을 무시하고 집행한다.
