[예외 4] Group B 자산 전략적 피라미딩: 최고가 대비 -10% 도달 시 Group A 매수를 중단하고 Group B 가중 매수(-20% 시 현금 10%, 추가 -5% 하락 시 남은 현금 20% 집행)로 전환한다.
